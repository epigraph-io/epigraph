-- no-transaction
--
-- 272's readable-claim arm (spec docs/superpowers/specs/
-- 2026-11-24-human-identity-visibility-design.md sections 6.1 and 11): for a
-- human principal H and a viewer whose group set is G, it probes, once per
-- agent ever bound to H, `LATERAL (SELECT 1 FROM claims c WHERE c.agent_id =
-- b.agent_id AND c.visibility <> 'public' AND c.owner_group_id = ANY (G)
-- LIMIT 1)`.
--
-- Key order (agent_id, owner_group_id): agent_id first matches that per-agent
-- probe (one descent per bound agent, the group set as array keys on the
-- second column), and it cannot be mistaken for a scan of a group's whole
-- partition, which is what idx_claims_group_current (063: owner_group_id,
-- is_current) would give for a viewer in a large group. Partial on the
-- non-public partition, as 063 is, so it covers the minority of rows.
--
-- INVALID-INDEX TRAP: a cancelled or failed CONCURRENTLY build leaves an
-- INVALID index of this name, and IF NOT EXISTS then skips it on a re-run.
-- Recovery: DROP INDEX CONCURRENTLY idx_claims_group_by_agent re-apply.
--
-- Exactly one statement (see 275).
-- Undo: DROP INDEX CONCURRENTLY IF EXISTS public.idx_claims_group_by_agent
CREATE INDEX CONCURRENTLY IF NOT EXISTS idx_claims_group_by_agent
    ON public.claims (agent_id, owner_group_id) WHERE visibility <> 'public';
