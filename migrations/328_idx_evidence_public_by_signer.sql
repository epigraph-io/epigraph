-- Operator ruling C6 (spec docs/superpowers/specs/
-- 2026-11-24-human-identity-visibility-design.md, sections 4, 11 and 16.R):
-- a PUBLIC assertion of any kind by H or by an agent bound to H names H, from
-- the agent's binding start (C5). 332's arm for evidence (its signer: the table has no author column) probes, once per agent
-- bound to H, `evidence.signer_id = b.agent_id AND visibility = 'public' AND evidence.created_at >= b.since LIMIT 1`.
-- No existing index serves it (none leads on signer_id with created_at under the
-- public predicate), so without this the probe walks every public row.
--
-- The predicate is written exactly as the arm writes it (partial-index
-- implication is proved syntactically).
--
-- INVALID-INDEX TRAP: a cancelled or failed CONCURRENTLY build leaves an
-- INVALID index of this name, and IF NOT EXISTS then skips it on a re-run.
-- Recovery: DROP INDEX CONCURRENTLY idx_evidence_public_by_signer, re-apply.
--
-- Exactly one statement (see 312).
-- Undo: DROP INDEX CONCURRENTLY IF EXISTS public.idx_evidence_public_by_signer
CREATE INDEX CONCURRENTLY IF NOT EXISTS idx_evidence_public_by_signer
    ON public.evidence (signer_id, created_at) WHERE visibility = 'public';
