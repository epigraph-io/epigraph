-- Operator ruling C6 (spec docs/superpowers/specs/
-- 2026-11-24-human-identity-visibility-design.md, sections 4, 11 and 16.R):
-- a PUBLIC assertion of any kind by H or by an agent bound to H names H, from
-- the agent's binding start (C5). 295's arm for BBAs (mass functions) probes, once per agent
-- bound to H, `mass_functions.source_agent_id = b.agent_id AND visibility = 'public' AND mass_functions.created_at >= b.since LIMIT 1`.
-- No existing index serves it (none leads on source_agent_id with created_at under the
-- public predicate), so without this the probe walks every public row.
--
-- The predicate is written exactly as the arm writes it (partial-index
-- implication is proved syntactically).
--
-- INVALID-INDEX TRAP: a cancelled or failed CONCURRENTLY build leaves an
-- INVALID index of this name, and IF NOT EXISTS then skips it on a re-run.
-- Recovery: DROP INDEX CONCURRENTLY idx_mass_functions_public_by_source, re-apply.
--
-- Exactly one statement (see 275).
-- Undo: DROP INDEX CONCURRENTLY IF EXISTS public.idx_mass_functions_public_by_source
CREATE INDEX CONCURRENTLY IF NOT EXISTS idx_mass_functions_public_by_source
    ON public.mass_functions (source_agent_id, created_at) WHERE visibility = 'public';
