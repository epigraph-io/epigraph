-- probes it.
--
-- INVALID-INDEX TRAP: a cancelled or failed CONCURRENTLY build leaves an
-- INVALID index of this name, and IF NOT EXISTS then skips it on a re-run.
-- Recovery: DROP INDEX CONCURRENTLY idx_claims_group_by_agent_since, re-apply.
--
-- Exactly one statement (see 277).
-- Undo: DROP INDEX CONCURRENTLY IF EXISTS public.idx_claims_group_by_agent_since
CREATE INDEX CONCURRENTLY IF NOT EXISTS idx_claims_group_by_agent_since
    ON public.claims (agent_id, owner_group_id, created_at) WHERE visibility <> 'public';
