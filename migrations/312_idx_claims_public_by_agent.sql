-- no-transaction
--
-- 309's public-claim arm (spec docs/superpowers/specs/
-- 2026-11-24-human-identity-visibility-design.md sections 6.1 and 11): for a
-- human principal H it probes, once per agent ever bound to H, "has this agent
-- filed any public claim?" with `LATERAL (SELECT 1 FROM claims c WHERE
-- c.agent_id = b.agent_id AND c.visibility = 'public' LIMIT 1)`.
--
-- Why no existing index serves it: idx_claims_agent_id (agent_id) and
-- idx_claims_agent_created (agent_id, created_at) carry no visibility, so for a
-- fleet agent with many group-only claims and no public one the probe walks
-- every claim of that agent with a heap check. Partial on the public
-- partition, so the probe is one descent that either finds a row or not.
--
-- The predicate is written `visibility = 'public'` exactly as the arm writes
-- it: the planner proves partial-index implication syntactically.
--
-- INVALID-INDEX TRAP: a cancelled or failed CONCURRENTLY build leaves an
-- INVALID index of this name, and IF NOT EXISTS then skips it on a re-run.
-- Recovery: DROP INDEX CONCURRENTLY idx_claims_public_by_agent re-apply.
-- `tenancy_migration_shape.rs` checks `indisvalid` on test databases.
--
-- Exactly one statement: a `-- no-transaction` file runs as one simple query,
-- and CREATE INDEX CONCURRENTLY refuses a multi-statement implicit transaction.
-- Undo: DROP INDEX CONCURRENTLY IF EXISTS public.idx_claims_public_by_agent
CREATE INDEX CONCURRENTLY IF NOT EXISTS idx_claims_public_by_agent
    ON public.claims (agent_id) WHERE visibility = 'public';
